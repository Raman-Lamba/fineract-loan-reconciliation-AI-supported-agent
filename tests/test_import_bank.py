HEADER = "Date,Narration,Chq./Ref.No.,Value Dt,Withdrawal Amt.,Deposit Amt.,Closing Balance"
UPI = "05/09/26,UPI-RAMESH KUMAR-ramesh@okaxis-UTIB0000001-507296189749-emi sep,0000507296189749,05/09/26,,\"8,450.00\",\"8,450.00\""
NEFT = "06/09/26,NEFT CR-SBIN0000001-LAKSHMI SHARMA-SCPL-SBINR52026090600001,SBINR52026090600001,06/09/26,,3100.50,\"11,550.50\""
DEBIT = "06/09/26,SMS CHARGES,0000000000000000,06/09/26,590.00,,\"10,960.50\""


def run(*rows, header=HEADER):
    return convert(io.StringIO("\n".join([header, *rows]) + "\n", newline=""))


class ImportTest(unittest.TestCase):
    def assertRefuses(self, row_no, part, *rows, **kw):
        with self.assertRaises(ValueError) as caught:
            run(*rows, **kw)
        self.assertIn(f"row {row_no}:", str(caught.exception))
        self.assertIn(part, str(caught.exception))

    def test_one_credit(self):
        lines, counts = run(UPI)
        self.assertEqual(lines, [{"txn_id": "507296189749", "date": "2026-09-05", "amount": "8450.00",
                                  "narration": "UPI-RAMESH KUMAR-ramesh@okaxis-UTIB0000001-507296189749-emi sep"}])
        self.assertEqual(counts, {"rows": 1, "credits": 1, "debits": 0, "empty": 0})

    def test_preamble_and_footer_are_skipped(self):
        text = "\n".join([
            "SAMPLE BANK,,,,,,", "Account No : 50200000000000,,,,,,", "Statement From : 01/09/26 To : 30/09/26", "",
            HEADER, "********,********,********,********,********,********,********",
            UPI, DEBIT, NEFT,
            "********,********,********,********,********,********,********",
            "STATEMENT SUMMARY :-", "Opening Balance,Dr Count,Cr Count,Debits,Credits,Closing Bal",
            "0.00,1,2,590.00,\"11,550.50\",\"10,960.50\"", ""])
        lines, counts = convert(io.StringIO(text, newline=""))
        self.assertEqual([r["txn_id"] for r in lines], ["507296189749", "SBINR52026090600001"])
        self.assertEqual(counts, {"rows": 3, "credits": 2, "debits": 1, "empty": 0})

    def test_footer_text_straight_after_the_last_row_ends_the_table(self):
        lines, _ = run(UPI, "STATEMENT SUMMARY :-", "Generated by: synthetic")
        self.assertEqual(len(lines), 1)

    def test_a_dated_row_after_the_table_ended_is_refused(self):
        self.assertRefuses(4, "after the end of the table", UPI, "", NEFT)

    def test_headers_in_another_order(self):
        lines, _ = run("\"8,450.00\",0000507296189749,x,05/09/26,,05/09/26,UPI-RAMESH KUMAR-r@okaxis",
                       header=" Closing Balance ,Chq./Ref.No.,Extra,Value Dt,Withdrawal Amt., date ,NARRATION,Deposit Amt.")
        self.assertEqual(lines, [])  # the deposit column is missing from the row: no credit

        lines, _ = run("\"8,450.00\",0000507296189749,x,05/09/26,,05/09/26,UPI-RAMESH KUMAR-r@okaxis,8450",
                       header=" Closing Balance ,Chq./Ref.No.,Extra,Value Dt,Withdrawal Amt., date ,NARRATION,Deposit Amt.")
        self.assertEqual(lines, [{"txn_id": "507296189749", "date": "2026-09-05", "amount": "8450.00",
                                  "narration": "UPI-RAMESH KUMAR-r@okaxis"}])

    def test_no_header_row_is_refused(self):
        with self.assertRaises(ValueError) as caught:
            convert(io.StringIO("Date,Description,Amount\n05/09/26,x,1\n", newline=""))
        self.assertIn("Chq./Ref.No.", str(caught.exception))

    def test_quoted_narration_with_commas_and_a_line_break(self):
        lines, _ = run('05/09/26,"NEFT CR-SBIN0000001-RAMESH KUMAR-SCPL COLLECTIONS A/C,\n MUMBAI-X1",0000000000000012,05/09/26,,8450.00,8450.00',
                       NEFT)
        self.assertEqual(lines[0]["narration"], "NEFT CR-SBIN0000001-RAMESH KUMAR-SCPL COLLECTIONS A/C, MUMBAI-X1")
        self.assertEqual(lines[0]["txn_id"], "12")
        self.assertEqual(len(lines), 2)

    def test_dates(self):
        for cell, iso in (("05/09/26", "2026-09-05"), ("31/01/26", "2026-01-31"), ("05/09/2026", "2026-09-05")):
            lines, _ = run(UPI.replace("05/09/26,UPI", f"{cell},UPI"))
            self.assertEqual(lines[0]["date"], iso)

    def test_indian_thousands_separators(self):
        for cell, amount in (('"1,21,940.65"', "121940.65"), ('"12,34,567"', "1234567.00"), ("950.5", "950.50"),
                             ('"1,234,567.00"', "1234567.00")):
            lines, _ = run(f"05/09/26,UPI-A B-a@ybl,77,05/09/26,,{cell},0")
            self.assertEqual(lines[0]["amount"], amount)

    def test_debits_and_rows_without_an_amount_are_skipped_and_counted(self):
        lines, counts = run(DEBIT, UPI, "07/09/26,OPENING ENTRY,,07/09/26,,,0.00", DEBIT)
        self.assertEqual(len(lines), 1)
        self.assertEqual(counts, {"rows": 4, "credits": 1, "debits": 2, "empty": 1})

    def test_duplicate_lines_are_kept_for_the_matcher_to_ignore(self):
        lines, _ = run(UPI, UPI)
        self.assertEqual([r["txn_id"] for r in lines], ["507296189749"] * 2)

    # Refusals: the row number counts every row of the file, header included, as Excel shows it.
    def test_credit_without_a_reference_is_kept_with_a_marked_stable_id(self):
        cash = "06/09/26,CASH DEPOSIT,0000000000000000,06/09/26,,500.00,0"
        lines, counts = run(UPI, cash, "06/09/26,CHQ DEPOSIT,,06/09/26,,700.00,0")
        self.assertEqual(len(lines), 3)
        self.assertRegex(lines[1]["txn_id"], r"^NOREF-2026-09-06-[0-9a-f]{8}$")
        self.assertEqual(lines[1]["amount"], "500.00")
        self.assertEqual((counts["credits"], counts["no_reference"]), (3, [3, 4]))
        self.assertEqual(run(cash)[0][0]["txn_id"], lines[1]["txn_id"])  # a re-import gives the same id

    def test_identical_rows_without_a_reference_stay_distinct_and_stable(self):
        cash = "06/09/26,CASH DEPOSIT,,06/09/26,,500.00,0"
        ids = [r["txn_id"] for r in run(cash, cash)[0]]
        self.assertEqual(len(set(ids)), 2)
        self.assertEqual(ids, [r["txn_id"] for r in run(cash, cash)[0]])

    def test_the_count_is_absent_when_every_credit_has_a_reference(self):
        self.assertNotIn("no_reference", run(UPI)[1])

    def test_credit_with_an_unreadable_amount_is_refused(self):
        for cell in ("8450.00 Cr", "8.450,00", '"84,50.00"', "-8450.00", "8450.001"):
            self.assertRefuses(3, "amount", UPI, f"06/09/26,UPI-A B-a@ybl,77,06/09/26,,{cell},0")

    def test_credit_with_an_unreadable_date_is_refused(self):
        for cell in ("32/09/26", "2026-09-05", "5 Sep 26", ""):
            self.assertRefuses(2, "date", f"{cell},UPI-A B-a@ybl,77,06/09/26,,8450.00,0")

    def test_row_with_both_a_withdrawal_and_a_deposit_is_refused(self):
        self.assertRefuses(2, "both", "06/09/26,UPI-A B-a@ybl,77,06/09/26,10.00,8450.00,0")

    # txn_id
    def test_reference_falls_back_to_the_one_long_number_in_the_narration(self):
        lines, _ = run("05/09/26,UPI-RAMESH KUMAR-9876543210@ybl-UTIB0000001-007296189749-emi,0000000000000000,05/09/26,,8450.00,0")
        self.assertEqual(lines[0]["txn_id"], "7296189749")
        lines, _ = run("05/09/26,IMPS-507296189749-RAMESH KUMAR-123456789012-emi,,05/09/26,,8450.00,0")
        self.assertTrue(lines[0]["txn_id"].startswith("NOREF-"))  # two numbers: it does not guess which

    def test_two_references_that_differ_only_in_leading_zeros_are_refused(self):
        self.assertRefuses(3, "leading zeros", "05/09/26,UPI-A B-a@ybl,0077,05/09/26,,10.00,0",
                           "05/09/26,UPI-C D-c@ybl,077,05/09/26,,10.00,0")


