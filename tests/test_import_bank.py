LOAN = {"loan_ref": "L1", "loan_id": 1, "account_no": "000000001", "client_id": 1, "firstname": "Ramesh",
        "lastname": "Kumar", "instalments": [{"due": "2026-09-05", "amount": 8450.0}]}


class NarrationTest(unittest.TestCase):
    def test_every_table_entry_has_an_example(self):
        self.assertEqual(set(EXAMPLES), {(bank, entry[0]) for bank, entries in FORMATS.items() for entry in entries})

    def test_name_from_each_format(self):
        for (bank, prefix), narration in EXAMPLES.items():
            self.assertEqual(payer_name(narration, bank), "RAMESH KUMAR", f"{bank} {prefix}")

    def test_each_format_posts_to_the_loan(self):
        for (bank, prefix), narration in EXAMPLES.items():
            line = {"txn_id": "1", "date": "2026-09-05", "amount": "8450.00", "narration": narration}
            d, = decide([line], [LOAN], bank)
            self.assertEqual((d["outcome"], d["loan_ref"]), ("post", "L1"), f"{bank} {prefix}: {d['reason']}")

    def test_another_banks_format_or_a_short_narration_gives_no_name(self):
        self.assertEqual(payer_name("UPI-RAMESH KUMAR-ramesh@okaxis", "synthetic"), "")
        self.assertEqual(payer_name("NEFT CR-SBIN0000001", "hdfc"), "")
        self.assertEqual(payer_name("CHQ DEP 000123", "hdfc"), "")

    def test_loan_account_in_a_bank_nach_line_posts(self):
        line = {"txn_id": "1", "date": "2026-09-05", "amount": "8450.00",
                "narration": "NACH-CR-SCPL000000001-SEP EMI-UMRN HDFC7020000080609954"}
        for bank in FORMATS:
            d, = decide([line], [LOAN], bank)
            self.assertEqual((d["outcome"], d["loan_ref"]), ("post", "L1"))

    def test_payment_channel_of_bank_narrations(self):
        for narration, name in (("NEFT CR-SBIN0000001-RAMESH KUMAR-X", "NEFT"), ("INF/NEFT/X/Y/RAMESH", "NEFT"),
                                ("MMT/IMPS/1/x/RAMESH", "IMPS"), ("UPI-RAMESH KUMAR-neft@ybl", "UPI"),
                                ("NACH-CR-SCPL000000001", "NACH"), ("CHQ DEP 000123", "")):
            self.assertEqual(channel(narration), name)


def loan(i):
    months = [f"2026-{m:02d}-15" for m in range(3, 11)]
    return {"loan_ref": f"L{i:04d}", "loan_id": i, "account_no": f"{i:09d}", "client_id": i,
            "firstname": f"First{i}", "lastname": f"Last{i % 7}",
            "instalments": [{"due": d, "amount": 1000.0 + i * 1500} for d in months]}


class HdfcExportTest(unittest.TestCase):
    def setUp(self):
        self.schedules = [loan(i) for i in range(1, 121)]
        self.lines, _ = generate(self.schedules)
        out = io.StringIO(newline="")
        csv.writer(out).writerows(hdfc_export(self.lines))
        self.text = out.getvalue()
        self.imported, self.counts = convert(io.StringIO(self.text, newline=""))

    def test_import_gives_back_the_same_ids_dates_and_amounts(self):
        strip = lambda rows: [(r["txn_id"], r["date"], r["amount"]) for r in rows]  # noqa: E731
        self.assertEqual(strip(self.imported), strip(self.lines))

    def test_export_has_a_preamble_debits_and_a_comma_in_a_narration(self):
        rows = list(csv.reader(io.StringIO(self.text, newline="")))
        self.assertNotEqual(rows[0][0], "Date")
        self.assertGreater(self.counts["debits"], 0)
        self.assertEqual(self.counts["credits"], len(self.lines))
        self.assertTrue(any("," in r["narration"] for r in self.imported))
        self.assertTrue(any("," in cell for r in rows for cell in r[4:6]))  # thousands separators

    def test_matcher_decides_the_same_through_the_import(self):
        pick = lambda ds: [(d["txn_id"], d["outcome"], d["loan_ref"]) for d in ds]  # noqa: E731
        self.assertEqual(pick(decide(self.imported, self.schedules, "hdfc")),
                         pick(decide(self.lines, self.schedules)))


